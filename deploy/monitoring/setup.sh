#!/usr/bin/env bash
# TechpioAsset monitoring — first-time setup and safe re-run (v3.20).
#
#   ssh root@<vps> /opt/techpioasset/deploy/monitoring/setup.sh
#
# What it does, every time it runs (each step is idempotent):
#   1. Creates .env.monitoring next to this file if missing: generated Grafana
#      admin password, generated database passwords, the public host. Never
#      overwrites one that exists - edit it by hand to change settings.
#   2. Creates (or re-passwords) the read-only monitor role in every PioAssets
#      Postgres container it finds, production and staging. The role has
#      pg_monitor only: statistics views, never table rows.
#   3. Pulls the images and starts the stack.
#   4. Prints where Grafana is and where the password lives (not the password).
#
# It does NOT touch nginx. Adding the /grafana/ location is a one-line include
# in the site config - see README.md - because editing a live nginx config
# from a script is how a typo takes the whole site down.

set -euo pipefail
cd "$(dirname "$0")"

ENV_FILE=.env.monitoring
COMPOSE=(docker compose -f docker-compose.monitoring.yml --env-file "$ENV_FILE")

secret() { openssl rand -base64 36 | tr -d '/+=' | cut -c1-32; }

# ── 1. environment file ─────────────────────────────────────────────────────
if [[ ! -f "$ENV_FILE" ]]; then
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh on $(date -u +%Y-%m-%dT%H:%MZ). Edit by hand; never commit.

# Where Grafana is served (through the host's nginx, under /grafana/).
GRAFANA_PUBLIC_HOST=pioassets.com
GRAFANA_ADMIN_PASSWORD=$(secret)

# Read-only database role for postgres_exporter (created by setup.sh).
MONITOR_DB_USER=techpioasset_monitor
MONITOR_DB_PASSWORD_PROD=$(secret)
MONITOR_DB_PASSWORD_STAGING=$(secret)
MONITOR_DB_NAME_PROD=techpioasset
MONITOR_DB_NAME_STAGING=techpioasset

# Where alert emails go. Needs the SMTP lines below to actually send.
ALERT_EMAIL=
GRAFANA_SMTP_ENABLED=false
GRAFANA_SMTP_HOST=
GRAFANA_SMTP_USER=
GRAFANA_SMTP_PASSWORD=
GRAFANA_SMTP_FROM=
EOF
  echo "setup: wrote $ENV_FILE (mode 600)"
else
  echo "setup: $ENV_FILE exists, keeping it"
fi

# shellcheck disable=SC1090
set -a; source "$ENV_FILE"; set +a

# ── 2. monitor role in each database ────────────────────────────────────────
# container name → password variable → database-name variable
make_role() {
  local container="$1" password="$2" dbname_var="$3"
  if ! docker ps --format '{{.Names}}' | grep -qx "$container"; then
    echo "setup: $container not running - skipping its monitor role"
    return 0
  fi
  local pg_user pg_db
  pg_user="$(docker exec "$container" printenv POSTGRES_USER)"
  pg_db="$(docker exec "$container" printenv POSTGRES_DB)"
  # Record the real database name so the exporter connects to the right one.
  if ! grep -q "^${dbname_var}=${pg_db}$" "$ENV_FILE"; then
    sed -i "s|^${dbname_var}=.*|${dbname_var}=${pg_db}|" "$ENV_FILE"
  fi
  # Password passed as a psql variable, never interpolated into SQL text.
  docker exec -i "$container" psql -v ON_ERROR_STOP=1 -q -U "$pg_user" -d "$pg_db" \
    -v role="$MONITOR_DB_USER" -v pass="$password" <<'SQL'
SELECT format('CREATE ROLE %I LOGIN PASSWORD %L', :'role', :'pass')
  WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'role') \gexec
SELECT format('ALTER ROLE %I WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS', :'role', :'pass') \gexec
SELECT format('GRANT pg_monitor TO %I', :'role') \gexec
SELECT format('GRANT CONNECT ON DATABASE %I TO %I', current_database(), :'role') \gexec
SQL
  echo "setup: monitor role ready in $container ($pg_db)"
}

make_role techpioasset-postgres-1         "$MONITOR_DB_PASSWORD_PROD"    MONITOR_DB_NAME_PROD
make_role techpioasset-staging-postgres-1 "$MONITOR_DB_PASSWORD_STAGING" MONITOR_DB_NAME_STAGING

# Re-read: make_role may have corrected a database name.
set -a; source "$ENV_FILE"; set +a

# ── 3. the stack ────────────────────────────────────────────────────────────
"${COMPOSE[@]}" pull -q
"${COMPOSE[@]}" up -d
echo
"${COMPOSE[@]}" ps --format 'table {{.Name}}\t{{.Status}}'

# ── 4. where to look ────────────────────────────────────────────────────────
cat <<EOF

Grafana:    https://${GRAFANA_PUBLIC_HOST}/grafana/   (once the nginx include is in place - README.md)
Login:      admin / the GRAFANA_ADMIN_PASSWORD line in $(pwd)/$ENV_FILE
Prometheus: http://127.0.0.1:9090 on the server only (ssh -L 9090:127.0.0.1:9090 root@<vps>)
Targets:    curl -s http://127.0.0.1:9090/api/v1/targets | grep -o '"health":"[a-z]*"' | sort | uniq -c
EOF
