/**
 * Emits a migration that syncs every tenant's SYSTEM roles to the domain
 * permission matrix (v2.15).
 *
 * Why this exists: role grants are DB rows copied when a tenant is created,
 * and nothing revisits them - so a tenant created before a feature shipped
 * never receives its permission. This bit production twice (Finance missing
 * assets:dispose, Super Admin missing users:impersonate). The running API
 * cannot fix it: the roles tables sit behind FORCE row-level security, and
 * only migrations run as the database owner.
 *
 * Run this whenever the matrix changes, commit the migration it prints:
 *
 *   node scripts/generate-grant-sync-migration.mjs
 *
 * The output is idempotent (re-runs are no-ops) and touches system roles
 * only - custom roles a tenant built for itself are never altered.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  ALL_PERMISSIONS,
  READ_ONLY_ROLES,
  ROLE_LABELS,
  ROLE_PERMISSIONS,
  SYSTEM_ROLES,
  isReadOnlyPermission,
} from '@techpioasset/domain';

const lines = [
  '-- Grant sync (generated by scripts/generate-grant-sync-migration.mjs).',
  '-- Brings every tenant\'s SYSTEM roles up to the domain permission matrix:',
  '-- missing permission rows are created, missing grants added, grants the',
  '-- matrix no longer contains removed. Custom (non-system) roles untouched.',
  '',
];

/** Single-quote a literal for SQL, doubling any quote inside it. */
const sql = (value) => `'${String(value).replace(/'/g, "''")}'`;

// 0. Roles a tenant never received (v2.43).
//
//    Roles are rows copied when a tenant is created, so a role added to the
//    matrix afterwards simply does not exist for anybody already running - and
//    a grant has nothing to attach to. This shipped the vendor portal to a
//    tenant with no Vendor role: every permission present, nothing able to hold
//    them. One row per company that is missing it, named exactly as the seed
//    would have named it.
for (const roleKey of SYSTEM_ROLES) {
  const label = ROLE_LABELS[roleKey];
  const isReadOnly = READ_ONLY_ROLES.includes(roleKey);
  lines.push(
    `INSERT INTO "roles" ("id", "companyId", "key", "name", "description", "isSystem", "isReadOnly", "createdAt", "updatedAt")` +
      ` SELECT gen_random_uuid()::text, c.id, ${sql(roleKey)}, ${sql(label.name)}, ${sql(label.description)}, true, ${isReadOnly}, now(), now()` +
      ` FROM "companies" c WHERE NOT EXISTS (` +
      `SELECT 1 FROM "roles" r WHERE r."companyId" = c.id AND r."key" = ${sql(roleKey)});`,
  );
}
lines.push('');

// 1. Permission rows for anything new. gen_random_uuid() only stands in for
//    the client-side cuid; nothing depends on the id's shape.
for (const key of ALL_PERMISSIONS) {
  const [resource, ...rest] = key.split(':');
  const action = rest.join(':');
  lines.push(
    `INSERT INTO "permissions" ("id", "key", "resource", "action", "isReadOnly", "description")` +
      ` SELECT gen_random_uuid()::text, '${key}', '${resource}', '${action}', ${isReadOnlyPermission(key)}, '${action} on ${resource}'` +
      ` WHERE NOT EXISTS (SELECT 1 FROM "permissions" WHERE "key" = '${key}');`,
  );
}
lines.push('');

// 2. Per system role: add what the matrix grants, drop what it no longer does.
for (const roleKey of SYSTEM_ROLES) {
  const grants = ROLE_PERMISSIONS[roleKey];
  lines.push(`-- ${roleKey}: ${grants.length} grants`);
  if (grants.length === 0) {
    // A zero-grant role (VENDOR): nothing to add, and every grant it somehow
    // holds is stale. An empty IN () is a syntax error, hence the split.
    lines.push(
      `DELETE FROM "role_permissions" rp USING "roles" r` +
        ` WHERE rp."roleId" = r.id AND r."key" = '${roleKey}' AND r."isSystem" = true;`,
    );
    lines.push('');
    continue;
  }
  const keyList = grants.map((k) => `'${k}'`).join(', ');
  lines.push(
    `INSERT INTO "role_permissions" ("roleId", "permissionId")` +
      ` SELECT r.id, p.id FROM "roles" r CROSS JOIN "permissions" p` +
      ` WHERE r."key" = '${roleKey}' AND r."isSystem" = true AND p."key" IN (${keyList})` +
      ` ON CONFLICT DO NOTHING;`,
  );
  lines.push(
    `DELETE FROM "role_permissions" rp USING "roles" r` +
      ` WHERE rp."roleId" = r.id AND r."key" = '${roleKey}' AND r."isSystem" = true` +
      ` AND rp."permissionId" NOT IN (SELECT id FROM "permissions" WHERE "key" IN (${keyList}));`,
  );
  lines.push('');
}

const stamp = new Date()
  .toISOString()
  .replace(/[-:TZ.]/g, '')
  .slice(0, 14);
const dir = path.join(import.meta.dirname, '..', 'prisma', 'migrations', `${stamp}_grant_sync`);
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, 'migration.sql'), lines.join('\n'));
console.log(`written: ${dir}/migration.sql`);
console.log(`${ALL_PERMISSIONS.length} permissions, ${SYSTEM_ROLES.length} system roles`);
